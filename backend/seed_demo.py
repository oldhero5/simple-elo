"""
Load the synthetic demo force into a separate demo database.

    python seed_demo.py --reset
    DATABASE_URL=../data/elo_demo.db uvicorn main:app

Reads the simulation's CSVs where they sit; none of it is copied into the repo.
Nothing here is Army data. The performance track is the simulation's comparison
record, replayed unchanged and checked against the simulation's own ratings. The
simulation has no potential answers, so this script generates that track and
labels it as generated.
"""

import argparse
import csv
import json
import os
import tempfile
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np

DEFAULT_SOURCE = (
    Path.home()
    / "Library/CloudStorage/OneDrive-Personal/Elo/Fellowship Package/Simulation"
)
DEMO_DB = Path(__file__).resolve().parent.parent / "data" / "elo_demo.db"

POTENTIAL_SEED = 20260606
POTENTIAL_SAMPLE = 1 / 3  # share of the simulation's pairs asked about potential
POTENTIAL_LOADING = 0.6  # correlation of potential with performance (assumption)
BETA = 1.64  # the simulation's base case: 80% pair accuracy
BAND_SD = {"tactical": 1.0, "operational": 0.85, "strategic": 0.70}

LABEL = "SYNTHETIC DEMO DATA. Not Army data. No real officers."
NOTES = [
    "3,000 simulated officers, 20 units, 12 quarters, from the Army Elo simulation.",
    "Performance comparisons are the simulation's record, loaded unchanged.",
    "Potential answers are generated by seed_demo.py, not the simulation: "
    "a third of the pairs, with an assumed 0.6 correlation to performance.",
    "The simulation models no ties or can't-judge answers, so both start at zero.",
    "All figures depend on the simulation's assumptions, including 80% pair accuracy.",
]

RATING_FIELDS = [
    "id",
    "round_id",
    "ratee_a_id",
    "ratee_b_id",
    "winner_id",
    "ratee_a_elo_before",
    "ratee_b_elo_before",
    "ratee_a_elo_after",
    "ratee_b_elo_after",
    "rated_at",
    "track",
    "quarter",
    "band",
    "unit_a",
    "unit_b",
    "cross_unit",
    "outcome",
]


def unit_label(index) -> str:
    return f"U{int(index) + 1:02d}"


def read_csv(path: Path) -> list[dict]:
    with open(path, newline="") as handle:
        return list(csv.DictReader(handle))


def potential_comparisons(comparisons, officers):
    """Generate the potential track from a sample of the simulation's pairs."""
    rng = np.random.default_rng(POTENTIAL_SEED)
    noise = rng.standard_normal(len(officers))
    latent = [
        POTENTIAL_LOADING * float(o["true_theta_q1"]) / BAND_SD[o["band"]]
        + (1 - POTENTIAL_LOADING**2) ** 0.5 * noise[i]
        for i, o in enumerate(officers)
    ]
    sampled = []
    for row in comparisons:
        if rng.random() >= POTENTIAL_SAMPLE:
            continue
        a, b = int(row["officer_a"]), int(row["officer_b"])
        p_a = 1 / (1 + np.exp(-BETA * (latent[a] - latent[b])))
        sampled.append({**row, "a_wins": str(int(rng.random() < p_a))})
    return sampled


def score_track(track, comparisons, rounds, next_rating_id, start_rating=1000.0):
    """Replay one track in record order. Returns rows, snapshots and final ratings."""
    ratings: dict[int, float] = {}
    rows, quarter_start = [], {}
    for comparison in comparisons:
        quarter = int(comparison["quarter"])
        if quarter not in quarter_start:
            quarter_start[quarter] = dict(ratings)
        a, b = int(comparison["officer_a"]), int(comparison["officer_b"])
        before_a = ratings.get(a, start_rating)
        before_b = ratings.get(b, start_rating)
        a_wins = comparison["a_wins"] == "1"
        expected = 1 / (1 + 10 ** ((before_b - before_a) / 400))
        delta = 32 * (float(a_wins) - expected)
        ratings[a], ratings[b] = before_a + delta, before_b - delta
        rows.append(
            {
                "id": next_rating_id + len(rows),
                "round_id": rounds[(track, quarter)]["id"],
                "ratee_a_id": a + 1,
                "ratee_b_id": b + 1,
                "winner_id": (a if a_wins else b) + 1,
                "ratee_a_elo_before": repr(before_a),
                "ratee_b_elo_before": repr(before_b),
                "ratee_a_elo_after": repr(ratings[a]),
                "ratee_b_elo_after": repr(ratings[b]),
                "rated_at": rounds[(track, quarter)]["dtg"].isoformat(sep=" "),
                "track": track,
                "quarter": quarter,
                "band": comparison["band"],
                "unit_a": unit_label(comparison["unit_a"]),
                "unit_b": unit_label(comparison["unit_b"]),
                "cross_unit": "true" if comparison["cross_unit"] == "1" else "false",
                "outcome": "a_wins" if a_wins else "b_wins",
            }
        )
    return rows, quarter_start, ratings


def check_against_simulation(performance_rows, source: Path) -> float:
    """The loaded record must reproduce the simulation's ratings at every quarter."""
    expected = {
        int(r["officer_id"]): r
        for r in read_csv(source / "E_ratings_by_quarter.csv")
    }
    latest: dict[int, float] = {}
    worst = 0.0
    quarter = 1

    def compare(q: int) -> float:
        return max(
            (abs(v - float(expected[pid - 1][f"Q{q}"])) for pid, v in latest.items()),
            default=0.0,
        )

    for row in performance_rows:
        if row["quarter"] != quarter:
            worst = max(worst, compare(quarter))
            quarter = row["quarter"]
        latest[row["ratee_a_id"]] = float(row["ratee_a_elo_after"])
        latest[row["ratee_b_id"]] = float(row["ratee_b_elo_after"])
    return max(worst, compare(quarter))


def seed(source: Path, db_path: Path, reset: bool) -> dict:
    os.environ["DATABASE_URL"] = str(db_path)
    if db_path.exists():
        if not reset:
            raise SystemExit(f"{db_path} exists. Pass --reset to rebuild it.")
        db_path.unlink()

    from bands import band_for_rank
    from database import Database

    database = Database(str(db_path))
    officers = read_csv(source / "E_officers.csv")
    comparisons = read_csv(source / "E_comparisons.csv")
    for officer in officers:
        if band_for_rank(officer["grade"]) != officer["band"]:
            raise SystemExit(f"Band mismatch: {officer}")

    tracks = {
        "performance": comparisons,
        "potential": potential_comparisons(comparisons, officers),
    }
    quarters = sorted({int(c["quarter"]) for c in comparisons})
    base = datetime(2000, 1, 1)  # placeholder: simulated quarters have no dates

    rounds = {}
    for track in tracks:
        for quarter in quarters:
            rounds[(track, quarter)] = {
                "id": len(rounds) + 1,
                "dtg": base + timedelta(days=91 * quarter),
            }

    all_rows, final, snapshots = [], {}, {}
    for track, records in tracks.items():
        rows, quarter_start, ratings = score_track(
            track, records, rounds, len(all_rows) + 1
        )
        all_rows += rows
        final[track] = ratings
        snapshots[track] = quarter_start

    drift = check_against_simulation(
        [r for r in all_rows if r["track"] == "performance"], source
    )
    if drift > 1e-6:
        raise SystemExit(f"Record does not reproduce the simulation: {drift}")

    with database.get_connection() as conn, tempfile.TemporaryDirectory() as tmp:
        people = Path(tmp) / "personnel.csv"
        with open(people, "w", newline="") as handle:
            writer = csv.writer(handle)
            writer.writerow(
                "id name rank band unit current_elo current_potential synthetic".split()
            )
            for i, officer in enumerate(officers):
                writer.writerow(
                    [
                        i + 1,
                        f"Synthetic Officer {i + 1:04d}",
                        officer["grade"],
                        officer["band"],
                        unit_label(officer["unit_q12"]),
                        repr(final["performance"].get(i, 1000.0)),
                        repr(final["potential"].get(i, 1000.0)),
                        "true",
                    ]
                )
        conn.execute(
            f"""
            COPY personnel (id, name, rank, band, unit, current_elo,
                            current_potential, synthetic)
            FROM '{people}' (HEADER)
            """
        )

        for (track, quarter), info in rounds.items():
            start = snapshots[track].get(quarter, {})
            snapshot = [
                {
                    "id": i + 1,
                    "name": f"Synthetic Officer {i + 1:04d}",
                    "rank": o["grade"],
                    "band": o["band"],
                    "unit": unit_label(o["unit_q12"]),
                    "current_elo": start.get(i, 1000.0),
                }
                for i, o in enumerate(officers)
            ]
            count = sum(int(c["quarter"]) == quarter for c in tracks[track])
            conn.execute(
                """
                INSERT INTO rounds (id, round_name, dtg, status, total_matchups,
                                    completed_matchups, personnel_snapshot, track,
                                    quarter, created_at)
                VALUES (?, ?, ?, 'completed', ?, ?, ?, ?, ?, ?)
                """,
                (
                    info["id"],
                    f"Synthetic Q{quarter:02d} {track}",
                    info["dtg"],
                    count,
                    count,
                    json.dumps(snapshot),
                    track,
                    quarter,
                    info["dtg"],
                ),
            )

        record = Path(tmp) / "ratings.csv"
        with open(record, "w", newline="") as handle:
            writer = csv.DictWriter(handle, RATING_FIELDS)
            writer.writeheader()
            writer.writerows(all_rows)
        conn.execute(
            f"COPY ratings ({', '.join(RATING_FIELDS)}) FROM '{record}' (HEADER)"
        )

        # Rows above carry explicit ids; move the sequences past them.
        for sequence, used in (
            ("personnel_id_seq", len(officers)),
            ("rounds_id_seq", len(rounds)),
            ("ratings_id_seq", len(all_rows)),
        ):
            conn.execute(f"SELECT max(nextval('{sequence}')) FROM range({used})")

        for key, value in {
            "synthetic": "true",
            "label": LABEL,
            "source": "Army Elo simulation, experiment E (seed 20260505)",
            "notes": json.dumps(NOTES),
        }.items():
            conn.execute("INSERT INTO dataset_meta VALUES (?, ?)", (key, value))

    return {
        "officers": len(officers),
        "performance_comparisons": len(tracks["performance"]),
        "potential_comparisons": len(tracks["potential"]),
        "max_drift_from_simulation": drift,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--source",
        type=Path,
        default=Path(os.getenv("ELO_SIM_DIR", DEFAULT_SOURCE)),
        help="folder holding the simulation's E_*.csv files",
    )
    parser.add_argument("--db", type=Path, default=DEMO_DB, help="demo database path")
    parser.add_argument("--reset", action="store_true", help="rebuild the demo db")
    args = parser.parse_args()
    print(json.dumps(seed(args.source, args.db, args.reset), indent=2))


if __name__ == "__main__":
    main()
