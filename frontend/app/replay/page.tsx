'use client'

import { useMemo, useState } from 'react'
import { Filters, Replay, Track, n1, n0, useApi } from '@/lib/api'
import RangeChart from '@/components/RangeChart'
import { ErrorRetry, PageHead } from '@/components/ui'

const TARGET = 5

function Tile({ label, value, note, status }: { label: string; value: string; note: string; status?: { met: boolean } }) {
  return (
    <div className="border-t border-line-strong pt-3">
      <div className="tele">{label}</div>
      <div className="mt-2 font-mono text-4xl tabular-nums tracking-tight sm:text-5xl">{value}</div>
      <p className="mt-2 text-[13px] leading-snug text-t2">{note}</p>
      {status && (
        <p className={`mt-3 font-mono text-[11px] uppercase tracking-tele ${status.met ? 'text-signal' : 'text-alert'}`}>
          Target under {TARGET} points: [{status.met ? 'MET' : 'NOT MET'}]
        </p>
      )}
    </div>
  )
}

export default function ReplayPage() {
  const [band, setBand] = useState('tactical')
  const [track, setTrack] = useState<Track>('performance')
  const [unit, setUnit] = useState('')
  const [through, setThrough] = useState('')
  const [shuffles, setShuffles] = useState(100)
  const filters = useApi<Filters>('/api/filters')

  const q = new URLSearchParams({ band, track, shuffles: String(shuffles), limit: '60' })
  if (unit) q.set('unit', unit)
  if (through) q.set('through_quarter', through)
  const rep = useApi<Replay>(`/api/replay?${q}`)

  const top = useMemo(() => [...(rep.data?.officers ?? [])].sort((a, b) => b.mean - a.mean).slice(0, 30), [rep.data])
  const s = rep.data?.summary
  const met = s?.median_sd_of_mean != null ? s.median_sd_of_mean < TARGET : undefined
  const stale = rep.loading && rep.data

  return (
    <div className="space-y-10">
      <PageHead
        title="Replay the record in shuffled order."
        sub="Elo depends on the order comparisons arrive. This replays one band's recorded answers many times, shuffled within each quarter, and measures how far each rating moves."
      />

      <div className="flex flex-wrap items-end gap-x-6 gap-y-3 border-y border-line py-4" role="group" aria-label="Replay settings">
        <div>
          <span className="tele mb-1 block">Track</span>
          <div className="seg">{(['performance', 'potential'] as Track[]).map(t => <button key={t} aria-pressed={track === t} onClick={() => setTrack(t)}>{t}</button>)}</div>
        </div>
        <div>
          <span className="tele mb-1 block">Band</span>
          <div className="seg">
            {(filters.data?.bands.map(b => b.band) ?? ['tactical', 'operational', 'strategic']).map(b => <button key={b} aria-pressed={band === b} onClick={() => setBand(b)}>{b}</button>)}
          </div>
        </div>
        <label className="block">
          <span className="tele mb-1 block">Unit</span>
          <select className="field !w-auto min-w-[88px] font-mono text-[13px]" value={unit} onChange={e => setUnit(e.target.value)}>
            <option value="">All units</option>
            {(filters.data?.units ?? []).map(u => <option key={u}>{u}</option>)}
          </select>
        </label>
        <label className="block">
          <span className="tele mb-1 block">Through quarter</span>
          <select className="field !w-auto min-w-[88px] font-mono text-[13px]" value={through} onChange={e => setThrough(e.target.value)}>
            <option value="">Last</option>
            {(filters.data?.quarters ?? []).map(x => <option key={x} value={x}>Q{x}</option>)}
          </select>
        </label>
        <label className="block min-w-[180px]">
          <span className="tele mb-1 flex justify-between"><span>Shuffles</span><span className="text-t1">{shuffles}</span></span>
          <input type="range" min={20} max={300} step={10} value={shuffles} onChange={e => setShuffles(Number(e.target.value))} className="w-full" />
        </label>
      </div>
      {track === 'potential' && (
        <p className="border-l-2 border-amber pl-3 text-[13px] text-t2">
          <span className="font-mono text-[11px] uppercase tracking-tele text-amber">[Seed script]</span> Potential answers are generated by the seed script, not the simulation.
        </p>
      )}

      {rep.error && <ErrorRetry message={rep.error} onRetry={rep.retry} label="Replay failed" />}

      {rep.loading && (
        <div role="status" className="flex items-center gap-3">
          <span className="relative block h-px w-32 overflow-hidden bg-line scanbar" aria-hidden />
          <span className="tele">Replaying {shuffles} shuffles</span>
        </div>
      )}

      {rep.data && s && (
        <div className={`space-y-10 transition-opacity duration-300 ${stale ? 'opacity-40' : ''}`} aria-busy={!!stale}>
          {s.officers === 0 ? (
            <p className="border border-line p-6 text-t2">No rated comparisons for this cut. Choose another band, unit or quarter.</p>
          ) : (
            <>
              <div className="grid gap-x-8 gap-y-8 sm:grid-cols-2 lg:grid-cols-4">
                <Tile label="Median sd, points" value={n1(s.median_sd)} note="How far a typical officer's rating moves across shuffles." />
                <Tile label="95th percentile sd, points" value={n1(s.p95_sd)} note="The move for the least stable one in twenty." />
                <Tile label={`sd of the ${rep.data.shuffles}-shuffle mean`} value={n1(s.median_sd_of_mean)} note="How far the average of this many shuffles would still move. Median across officers." status={met == null ? undefined : { met }} />
                <Tile label="Median rank sd, places" value={n1(s.median_rank_sd)} note="How many places a typical officer shifts in the order." />
              </div>
              <p className="border-l-2 border-line-strong pl-4 text-[15px] leading-relaxed text-t2">
                Averaging over shuffles makes a rating reproducible. It barely makes it more accurate: the replay measures order noise, not whether the answers were right.
              </p>
              <section aria-label="Per-officer range">
                <div className="mb-4 flex flex-wrap items-end justify-between gap-2">
                  <h2 className="display text-2xl sm:text-3xl">Top {top.length} officers by mean rating</h2>
                  <p className="tele">{n0(s.officers)} officers, {n0(s.comparisons)} comparisons, seed {rep.data.seed}</p>
                </div>
                <RangeChart officers={top} />
              </section>
            </>
          )}
        </div>
      )}
    </div>
  )
}
